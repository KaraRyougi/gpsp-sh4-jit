#!/usr/bin/env python3
"""Generate ports/fxcg100/txt_font_terminus.h from upstream Terminus BDF files
(ter-u12n.bdf and ter-u14n.bdf, SIL Open Font License 1.1).

Usage:
  python3 ports/fxcg100/tools/bdf_to_header.py ter-u12n.bdf ter-u14n.bdf \
      > ports/fxcg100/txt_font_terminus.h
"""

import sys
from pathlib import Path


def parse_fixed_bdf(path: Path):
    lines = path.read_text(encoding="latin-1").splitlines()
    fb_w = fb_h = fb_x = fb_y = 0
    font_asc = font_desc = None
    glyphs = {}

    i, n = 0, len(lines)
    while i < n:
        ln = lines[i]
        if ln.startswith("FONTBOUNDINGBOX "):
            fb_w, fb_h, fb_x, fb_y = map(int, ln.split()[1:5])
        elif ln.startswith("FONT_ASCENT "):
            font_asc = int(ln.split()[1])
        elif ln.startswith("FONT_DESCENT "):
            font_desc = int(ln.split()[1])
        elif ln.startswith("STARTCHAR"):
            enc = -1
            bw = bh = bx = by = 0
            bmap = []
            i += 1
            while i < n and not lines[i].startswith("ENDCHAR"):
                cl = lines[i]
                if cl.startswith("ENCODING "):
                    enc = int(cl.split()[1])
                elif cl.startswith("BBX "):
                    bw, bh, bx, by = map(int, cl.split()[1:5])
                elif cl == "BITMAP":
                    i += 1
                    while i < n and not lines[i].startswith("ENDCHAR"):
                        hs = lines[i].strip()
                        if hs:
                            bmap.append(bytes.fromhex(hs))
                        i += 1
                    continue
                i += 1
            if 32 <= enc <= 126:
                glyphs[enc] = (bw, bh, bx, by, bmap)
        i += 1

    if font_asc is None:
        font_asc = fb_h + fb_y
    if font_desc is None:
        font_desc = -fb_y
    cell_h = font_asc + font_desc
    if fb_w > 8:
        raise ValueError(f"{path}: width {fb_w} > 8 not supported by 1-byte/row layout")

    out = bytearray()
    for code in range(32, 127):
        rows = [0] * cell_h
        g = glyphs.get(code)
        if g:
            bw, bh, bx, by, bmap = g
            gtop = font_asc - (by + bh)
            for r in range(bh):
                py = gtop + r
                if 0 <= py < cell_h and r < len(bmap):
                    byte = bmap[r][0]
                    if bx > 0:
                        byte >>= bx
                    elif bx < 0:
                        byte = (byte << (-bx)) & 0xFF
                    rows[py] = byte
        out.extend(rows)

    return fb_w, cell_h, font_asc, font_desc, bytes(out)


def emit_array(name: str, data: bytes) -> str:
    lines = [f"static const uint8_t {name}[{len(data)}] = {{"]
    for off in range(0, len(data), 16):
        chunk = ",".join(f"0x{b:02X}" for b in data[off : off + 16])
        lines.append(f"\t{chunk},")
    lines.append("};")
    return "\n".join(lines)


def main():
    if len(sys.argv) != 3:
        sys.stderr.write("Usage: bdf_to_header.py ter-u12n.bdf ter-u14n.bdf\n")
        sys.exit(1)

    w12, h12, asc12, desc12, d12 = parse_fixed_bdf(Path(sys.argv[1]))
    w14, h14, asc14, desc14, d14 = parse_fixed_bdf(Path(sys.argv[2]))

    header = f"""#ifndef CGBA_TXT_FONT_TERMINUS_H
#define CGBA_TXT_FONT_TERMINUS_H

/* Generated by ports/fxcg100/tools/bdf_to_header.py - do not edit.
 *
 * Crisp 1-bit fixed-width bitmap fonts for the in-game TXT reader, extracted
 * from Terminus Font 4.49.1 (Copyright (C) 2020 Dimitar Zhekov, SIL Open Font
 * License 1.1; see ports/fxcg100/fonts/OFL.txt):
 *
 *   txt_font_terminus_6x12: ter-u12n.bdf ({w12}x{h12}, {len(d12)} bytes)
 *   txt_font_terminus_8x14: ter-u14n.bdf ({w14}x{h14}, {len(d14)} bytes)
 *
 * ASCII 32..126, 1 bit per pixel, 1 byte per row (MSB = leftmost pixel). */

#include <stdint.h>

#include "classpad_gfx.h"

typedef struct txt_bitmap_font {{
	uint8_t w, h;
	uint8_t asc, desc;
	const uint8_t *data;
}} txt_bitmap_font;

{emit_array("txt_font_terminus_6x12_data", d12)}

static const txt_bitmap_font txt_font_terminus_6x12 = {{
	{w12}, {h12}, {asc12}, {desc12}, txt_font_terminus_6x12_data
}};

{emit_array("txt_font_terminus_8x14_data", d14)}

static const txt_bitmap_font txt_font_terminus_8x14 = {{
	{w14}, {h14}, {asc14}, {desc14}, txt_font_terminus_8x14_data
}};

static inline int txt_draw_text_n(const cp_surface *s,
	const txt_bitmap_font *f, int x, int y, const char *text, int len,
	uint16_t color)
{{
	int i, gw = f->w, gh = f->h;

	x += s->ox;
	y += s->oy;
	for (i = 0; text[i] && (len < 0 || i < len); i++) {{
		int code = (unsigned char)text[i];
		const uint8_t *rows;
		int gy, gx;

		if (code < 32 || code > 126)
			code = '?';
		rows = f->data + (code - 32) * gh;
		for (gy = 0; gy < gh; gy++) {{
			int py = y + gy;
			uint8_t bits;

			if (py < s->clip.y || py >= s->clip.y + s->clip.h)
				continue;
			bits = rows[gy];
			if (!bits)
				continue;
			for (gx = 0; gx < gw; gx++) {{
				if (bits & (0x80u >> gx)) {{
					int px = x + gx;

					if (px >= s->clip.x && px < s->clip.x + s->clip.w)
						*cp_surface_pixel(s, px, py) = color;
				}}
			}}
		}}
		x += gw;
	}}
	return x - s->ox;
}}

static inline int txt_draw_text(const cp_surface *s,
	const txt_bitmap_font *f, int x, int y, const char *text, uint16_t color)
{{
	return txt_draw_text_n(s, f, x, y, text, -1, color);
}}

static inline int txt_draw_text_fit(const cp_surface *s,
	const txt_bitmap_font *f, int x, int y, int max_w, const char *text,
	uint16_t color)
{{
	int max_chars = max_w / (int)f->w;
	int len = 0;

	if (max_chars <= 0)
		return x;
	while (text[len] && len <= max_chars)
		len++;
	if (len <= max_chars)
		return txt_draw_text_n(s, f, x, y, text, len, color);
	if (max_chars <= 3)
		return txt_draw_text_n(s, f, x, y, text, max_chars, color);
	x = txt_draw_text_n(s, f, x, y, text, max_chars - 3, color);
	return txt_draw_text_n(s, f, x, y, "...", 3, color);
}}

#endif /* CGBA_TXT_FONT_TERMINUS_H */
"""
    sys.stdout.write(header)


if __name__ == "__main__":
    main()
